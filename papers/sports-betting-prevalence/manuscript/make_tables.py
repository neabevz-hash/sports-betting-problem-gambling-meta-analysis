"""Tables of the manuscript from the analysis results (analysis/results/*.csv, forms/samples.csv).

Writes manuscript/tables.md: Table 1 (characteristics of the samples in the meta-analyses), Table 2 (pooled prevalence
by case-definition level and subgroup), Table 3 (moderators and within-study contrasts), Table 4 (GRADE summary of
findings, rules in deviations.md C2), and Table S1 (every sample with its primary estimate) for the supplement.
Template: papers/misophonia-prevalence/manuscript/make_tables.py.
Run: .venv/Scripts/python.exe -I papers/sports-betting-prevalence/manuscript/make_tables.py
"""
from __future__ import annotations

import csv
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent
RES = PAPER / "analysis" / "results"
NOT_BETTORS = {"S009", "S015", "S034"}


def rows(name: str) -> list[dict]:
    return list(csv.DictReader((RES / name).open(encoding="utf-8")))


def f(x, d=1) -> str:
    try:
        return f"{float(x):.{d}f}"
    except (TypeError, ValueError):
        return "NA"


def pct(x, d=1) -> str:
    try:
        return f"{100 * float(x):.{d}f}"
    except (TypeError, ValueError):
        return "NA"


def pooled_line(r: dict, label: str) -> str:
    if r["prev"] in ("", "NA"):
        return f"| {label} | {r['k']} | {int(float(r['n_total'])):,} | not pooled (k < 3) | | |"
    return (f"| {label} | {r['k']} | {int(float(r['n_total'])):,} | {pct(r['prev'])} ({pct(r['ci.lb'])}–{pct(r['ci.ub'])}) | "
            f"{pct(r['pi.lb'])}–{pct(r['pi.ub'])} | {f(r['I2'])} |")


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    samples = [s for s in csv.DictReader((PAPER / "forms" / "samples.csv").open(encoding="utf-8"))]
    sel = rows("selection_log.csv")
    pooled_ids = {r["sample_id"] for r in sel if not r["analysis"].startswith("post hoc")}
    an = [s for s in samples if s["sample_id"] in pooled_ids]
    prim = {r["sample_id"]: r for r in sel if r["analysis"] == "primary L3/L4"}
    L = ["# Tables (generated by make_tables.py; do not edit by hand)", ""]

    # Table 1
    stype = {"rep_survey_subsample": "Bettors in representative surveys", "gamblers_survey_subsample":
             "Bettors in other surveys of gamblers", "bettor_recruited": "Bettors recruited as such",
             "students": "University students", "school_pupils": "School pupils", "athletes": "Student-athletes",
             "other": "Hospital outpatients"}
    n_tot = sum(float(s["n_bettors"]) for s in an if s["n_bettors"] not in ("NR", ""))
    L += [f"**Table 1.** Characteristics of the {len(an)} samples in the meta-analyses "
          f"({len({s['study_id'] for s in an})} studies; {int(n_tot):,} sports bettors where n was reported)", "",
          "| Characteristic | Samples, n (%) |", "| --- | --- |"]

    def block(title, counter, order=None, denom=None):
        L.append(f"| **{title}** | |")
        items = order or [k for k, _ in counter.most_common()]
        for k in items:
            if counter.get(k):
                L.append(f"| {k} | {counter[k]} ({100 * counter[k] / (denom or len(an)):.0f}) |")

    block("Sample type", Counter(stype.get(s["sample_type"], s["sample_type"]) for s in an))
    block("Sampling", Counter({"probability": "Probability", "census": "Census", "quota": "Quota online panel",
                               "convenience": "Convenience", "operator_customers": "Operator customers",
                               "venue_intercept": "Venue intercept", "snowball": "Snowball"}.get(s["sampling"], s["sampling"])
                              for s in an))
    block("Region", Counter((s["region"] or "Not reported").replace("multi", "Several countries") for s in an))
    block("Age group", Counter({"adults": "Adults", "mixed": "Adolescents and adults", "NR": "Not reported",
                                "adolescents": "Adolescents"}.get(s["age_group"], s["age_group"]) for s in an))
    block("Betting mode", Counter({"both": "Online and land-based", "online only": "Online only",
                                   "land-based only": "Land-based only", "NR": "Not reported"}.get(s["betting_mode"], s["betting_mode"])
                                  for s in an))
    block(f"Instrument of the primary estimate (of {len(prim)} samples)",
          Counter(prim[s["sample_id"]]["instrument"] for s in an if s["sample_id"] in prim), denom=len(prim))
    yrs = sorted(int(s["data_years"][:4]) for s in an if s["data_years"][:4].isdigit())
    L += [f"| **Data collection** | {yrs[0]}–{yrs[-1]}; not reported in {len(an) - len(yrs)} |",
          f"| **Published in a journal** | {sum(s['pub_status'] == 'journal' for s in an)} ({100 * sum(s['pub_status'] == 'journal' for s in an) / len(an):.0f}) |",
          "", "Percentages of the samples in the meta-analyses; for the instrument, of the samples with a primary (L3/L4) estimate.", ""]

    # Table 2
    pooled = {r["analysis"]: r for r in rows("pooled.csv")}
    L += ["**Table 2.** Pooled prevalence among sports bettors by case-definition level and subgroup (GLMM, logit link)", "",
          "| Outcome or subgroup | k | Bettors | Prevalence, % (95% CI) | 95% PI, % | I², % |", "| --- | --- | --- | --- | --- | --- |"]
    for key, lab in [("Level L1", "Any risk (L1; e.g., PGSI ≥ 1)"), ("Level L2", "Moderate risk or higher (L2; PGSI ≥ 3)"),
                     ("Primary: problem gambling (L3/L4)", "**Problem gambling (L3/L4; PGSI ≥ 8) — primary**")]:
        L.append(pooled_line(pooled[key], lab))
    L.append("| *Primary outcome by sample type* | | | | | |")
    for a, r in pooled.items():
        if a.startswith("Primary by sample type: "):
            L.append(pooled_line(r, "  " + a.split(": ", 1)[1].capitalize()))
    L.append("| *Primary outcome by region* | | | | | |")
    for a, r in pooled.items():
        if a.startswith("Primary by region: "):
            L.append(pooled_line(r, "  " + a.split(": ", 1)[1].replace("other", "Several countries")))
    L.append("| *Primary outcome by age group* | | | | | |")
    for a, r in pooled.items():
        if a.startswith("Primary by age group: "):
            L.append(pooled_line(r, "  " + a.split(": ", 1)[1].replace("mixed or NR", "Adolescents and adults, or not reported").capitalize()))
    for lv in ("L1", "L2"):
        L.append(f"| *{lv} by sample type* | | | | | |")
        for a, r in pooled.items():
            if a.startswith(f"Level {lv} by sample type: "):
                L.append(pooled_line(r, "  " + a.split(": ", 1)[1].capitalize()))
    st = {r["moderator"]: r for r in rows("subgroup_tests.csv")}
    b = rows("benchmark_tran.csv")[0]
    L += ["", f"Subgroup tests (GLMM, primary outcome): sample type QM = {f(st['stype']['QM'])}, df = {st['stype']['df']}, "
          f"p = {f(st['stype']['p'], 3)}; region QM = {f(st['regiongrp']['QM'])}, df = {st['regiongrp']['df']}, "
          f"p {"< 0.001" if float(st['regiongrp']['p']) < 0.001 else "= " + f(st['regiongrp']['p'], 3)}; age group QM = {f(st['agegrp']['QM'])}, p = {f(st['agegrp']['p'], 3)}. "
          f"Benchmark: Tran et al. (2024), adults who bet on sports in representative surveys, {pct(b['tran_prev'])}% "
          f"({pct(b['tran_ci.lb'])}–{pct(b['tran_ci.ub'])}). k, samples; PI, prediction interval.", ""]

    # Table 3
    L += ["**Table 3.** Moderators of prevalence (three-level binomial GLMM on all whole-sample estimates) and within-study contrasts", "",
          "| Moderator | Comparison | OR (95% CI) | p | Samples |", "| --- | --- | --- | --- | --- |"]
    names = {"levelL2": ("Level", "L2 vs L1"), "levelL3": ("Level", "L3 vs L1"), "levelL4": ("Level", "L4 vs L1"),
             "stypebettors in other gambler surveys": ("Sample type", "Other gambler surveys vs representative surveys"),
             "stypebettors recruited as such": ("Sample type", "Recruited as bettors vs representative surveys"),
             "stypestudents, pupils and other": ("Sample type", "Students, pupils and other vs representative surveys"),
             "probTRUE": ("Probability sampling", "Yes vs no")}
    for r in rows("multilevel_prespecified.csv"):
        if r["term"] in names:
            m, c = names[r["term"]]
            L.append(f"| {m} (pre-specified model) | {c} | {f(r['OR'], 2)} ({f(r['ci.lb'], 2)}–{f(r['ci.ub'], 2)}) | {"< 0.001" if float(r['p']) < 0.001 else f(r['p'], 3)} | |")
    ve = {r["model"]: r for r in rows("variance_explained.csv")}
    ex = {r["moderator"]: r for r in rows("moderators_exploratory.csv")}
    for r in rows("moderators_exploratory_coefs.csv"):
        if r["moderator"] in ("regiongrp", "age_z", "year_z", "regular", "online_only", "instrument", "funded", "journal"):
            lab = {"regiongrp": "Region (vs Europe)", "age_z": "Mean age", "year_z": "Year of data collection",
                   "regular": "Minimum betting frequency", "online_only": "Online-only bettors (vs both)",
                   "instrument": "PGSI vs other instrument (L3)", "funded": "Industry funding",
                   "journal": "Journal vs other"}[r["moderator"]]
            term = r["term"].replace(r["moderator"], "") or "per SD"
            term = {"TRUE": "journal article", "yes": "funded by industry", "PGSI": "PGSI", "other": "several countries",
                    "minimum frequency": "minimum required vs any bettor"}.get(term, term)
            L.append(f"| {lab} (exploratory, LRT p {"< 0.001" if float(ex[r['moderator']]['p']) < 0.001 else "= " + f(ex[r['moderator']]['p'], 3)}) | {term} | "
                     f"{f(r['OR'], 2)} ({f(r['ci.lb'], 2)}–{f(r['ci.ub'], 2)}) | {"< 0.001" if float(r['p']) < 0.001 else f(r['p'], 3)} | {r['n_samples_term']} |")
    L.append("| *Within-study contrasts (post hoc, descriptive)* | | | | |")
    for r in rows("within_study_contrasts.csv"):
        L.append(f"| {r['contrast'].capitalize()} | {r['study']}: {pct(r['prev_a'])}% ({r['cases_a']}/{r['n_a']}) vs "
                 f"{pct(r['prev_b'])}% ({r['cases_b']}/{r['n_b']}), {r['level']} | {f(r['OR'], 2)} ({f(r['ci.lb'], 2)}–{f(r['ci.ub'], 2)}) | | 1 study |")
    L += ["", f"Level alone explained {pct(ve['level']['pseudo_R2'], 0)}% of the between-estimate variance (logit scale); "
          f"level and sample type {pct(ve['level + sample type']['pseudo_R2'], 0)}%; adding probability sampling "
          f"{pct(ve['level + sample type + probability sampling']['pseudo_R2'], 0)}%. Exploratory moderators: one at a time, "
          "adjusted for level, tested only with at least 10 samples; LRT, likelihood-ratio test. Odds ratios for mean age and "
          "year are per standard deviation.", ""]

    # Table 4 (GRADE)
    g = rows("grade_inputs.csv")
    L += ["**Table 4.** Summary of findings and certainty of evidence (GRADE for event rates; thresholds in "
          "Supplementary File S3, clarification C2)", ""]
    short = {"Problem gambling (L3/L4), all samples": "Problem gambling (L3/L4)",
             "Problem gambling (L3/L4), bettors in representative surveys": "Problem gambling, representative surveys",
             "Moderate risk or higher (L2), all samples": "Moderate risk or higher (L2)",
             "Any risk (L1), all samples": "Any risk (L1)",
             "Male-to-female odds ratio at the primary level": "Male-to-female odds ratio"}
    cols = {k: [] for k in ("Samples (bettors)", "Estimate (95% CI)", "Risk of bias^a^", "Inconsistency^b^",
                            "Imprecision^c^", "Indirectness^d^", "Publication bias^e^", "Certainty")}
    for r in g:
        prev = r["measure"] == "prevalence"
        rob = float(r["weight_any_no"]) > 0.5
        if prev:
            inc = (float(r["pi.ub"]) - float(r["pi.lb"])) > 0.30
            imp = (float(r["ci.ub"]) - float(r["ci.lb"])) / 2 > 0.05
            est = f"{pct(r['estimate'])}% ({pct(r['ci.lb'])}–{pct(r['ci.ub'])})"
            pi = f"PI {pct(r['pi.lb'], 0)}–{pct(r['pi.ub'], 0)}%"
            hw = f"±{f(50 * (float(r['ci.ub']) - float(r['ci.lb'])))} points"
        else:
            inc = float(r["pi.lb"]) < 1 < float(r["pi.ub"])
            imp = float(r["ci.lb"]) < 1 < float(r["ci.ub"])
            est = f"OR {f(r['estimate'], 2)} ({f(r['ci.lb'], 2)}–{f(r['ci.ub'], 2)})"
            pi = f"PI {f(r['pi.lb'], 2)}–{f(r['pi.ub'], 2)}"
            hw = "CI includes 1"
        ind = int(r["countries"]) < 5 or int(r["regions"]) < 3
        pb = prev and r["small_study_p"] not in ("", "NA") and float(r["small_study_p"]) < 0.10
        down = sum([rob, inc, imp, ind, pb])
        yn = lambda x, why: f"{'Serious' if x else 'Not serious'} ({why})"
        cols["Samples (bettors)"].append(f"{r['k']} ({int(float(r['participants'])):,})")
        cols["Estimate (95% CI)"].append(est)
        cols["Risk of bias^a^"].append(yn(rob, pct(r["weight_any_no"], 0) + "%"))
        cols["Inconsistency^b^"].append(yn(inc, pi))
        cols["Imprecision^c^"].append(yn(imp, hw))
        cols["Indirectness^d^"].append(yn(ind, f"{r['countries']} countries, {r['regions']} regions"))
        cols["Publication bias^e^"].append(f"{'Suspected' if pb else 'Not detected'} (p = {f(r['small_study_p'], 2)})"
                                          if r["small_study_p"] not in ("", "NA") else "Not assessed (k < 10)")
        cols["Certainty"].append(f"**{['High', 'Moderate', 'Low', 'Very low', 'Very low', 'Very low'][down]}**")
    L += ["| | " + " | ".join(short.get(r["outcome"], r["outcome"]) for r in g) + " |",
          "| --- | " + " | ".join("---" for _ in g) + " |"]
    for k, v in cols.items():
        L.append(f"| {k} | " + " | ".join(v) + " |")
    L += ["", "^a^ Share of the inverse-variance weight from samples rated no on JBI items 2, 6 or 9 (serious above 50%). "
          "^b^ 95% prediction interval (prevalence: serious if wider than 30 percentage points; odds ratio: if it includes 1). "
          "^c^ Half-width of the 95% CI in percentage points (serious above 5) or, for the odds ratio, a CI including 1. "
          "^d^ Serious with fewer than five countries or three regions. "
          "^e^ Regression of logit prevalence on 1/√n, assessed with at least 10 samples. Certainty starts high for event "
          "rates (Iorio et al., 2015) and is rated down one level per serious domain.", ""]

    # Table S1
    L += ["**Table S1.** Samples in the review and their primary estimate (problem gambling, L3/L4)", "",
          "| Sample | Study | Country | Sample type | Sampling | n bettors | Instrument, threshold | Cases / n | % |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for s in samples:
        p = prim.get(s["sample_id"])
        tag = " (not sports bettors only; not pooled)" if s["sample_id"] in NOT_BETTORS else ""
        est = (f"{p['instrument']}, {p['threshold']} | {int(float(p['cases']))} / {int(float(p['n']))} | "
               f"{100 * float(p['cases']) / float(p['n']):.1f}") if p else "no L3/L4 count | | "
        L.append(f"| {s['sample_id']} | {s['first_author']} {s['year']} | {s['country'][:24]} | "
                 f"{stype.get(s['sample_type'], s['sample_type'])}{tag} | {s['sampling']} | {s['n_bettors']} | {est} |")
    (HERE / "tables.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"tables.md written: {len(an)} samples in the meta-analyses, {len(samples)} in Table S1")


if __name__ == "__main__":
    main()
